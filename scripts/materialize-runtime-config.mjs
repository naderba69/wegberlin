import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const registryPath=resolve(root,"src/config/curriculum-version.json");
const generatedTypeScriptPath=resolve(root,"src/config/curriculum-version.generated.ts");
const workerPath=resolve(root,"public/sw.js");
const registry=JSON.parse(await readFile(registryPath,"utf8"));
if(registry.policyVersion!=="independent-curriculum-version-v1"||typeof registry.currentCurriculumVersion!=="string"||!/^dwnb-a1-b2-/u.test(registry.currentCurriculumVersion))throw new Error("Invalid central curriculum-version registry.");

const generatedTypeScript=`// GENERATED from curriculum-version.json by scripts/materialize-runtime-config.mjs.\n// Do not edit this file manually.\nexport const GENERATED_CURRICULUM_VERSION_REGISTRY = ${JSON.stringify(registry,null,2)} as const;\n`;
let currentTypeScript="";try{currentTypeScript=await readFile(generatedTypeScriptPath,"utf8")}catch{/* generated below */}
if(currentTypeScript!==generatedTypeScript)await writeFile(generatedTypeScriptPath,generatedTypeScript);

const worker=await readFile(workerPath,"utf8");
const generatedWorkerLine=`// GENERATED from src/config/curriculum-version.json — do not edit this line manually.\nconst CURRICULUM_VERSION = ${JSON.stringify(registry.currentCurriculumVersion)};`;
const pattern=/(?:\/\/ GENERATED from src\/config\/curriculum-version\.json — do not edit this line manually\.\n)?const CURRICULUM_VERSION = "[^"]+";/u;
if(!pattern.test(worker))throw new Error("Service worker curriculum-version marker is missing.");
const nextWorker=worker.replace(pattern,generatedWorkerLine);
if(nextWorker!==worker)await writeFile(workerPath,nextWorker);
console.log(`Materialized TypeScript and Service Worker curriculum version: ${registry.currentCurriculumVersion}.`);
