const normalize = (text: string) => text.toLowerCase();
const LATIN = "A-Za-zÄÖÜäöüß";
const escapeRe = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");

/**
 * المطابقة على **كلمة كاملة** لا على سلسلة حروف: `r` و`ch` و`ein` ليست كلمات
 * دالة، ومطابقتها كأجزاء تُظهر الشرح في كل درس (وهو ما كشفه الاختبار أول مرة).
 */
const wordMatch = (haystack: string, keyword: string) =>
  new RegExp(`(?<![${LATIN}])${escapeRe(keyword.toLowerCase())}(?![${LATIN}])`, "u").test(haystack);

/**
 * المطابقة على **عنوان القاعدة وصيغتها** لا على مجال الدرس: الشرح يُعرض حيث
 * يظهر البناء فعلاً، فلا يُفرض على درس لا علاقة له به.
 */
export function tunisianNotesFor(block: Pick<TheoryBlock, "titleDe" | "titleAr" | "formula" | "explanationAr">): TunisianSupportNote[] {
  const haystack = normalize([block.titleDe, block.titleAr, block.formula ?? "", block.explanationAr].join(" "));
  return TUNISIAN_SUPPORT_NOTES.filter((note) =>
    note.keywordsDe.some((keyword) => wordMatch(haystack, keyword)),
  );
}

/** كم ملاحظة دعم تونسي يظهر في درس كامل؟ (مقياس للمدقق والاختبار) */
export function tunisianNoteCountForLesson(theory: readonly TheoryBlock[]): number {
  const ids = new Set<string>();
  for (const block of theory) for (const note of tunisianNotesFor(block)) ids.add(note.id);
  return ids.size;
}
